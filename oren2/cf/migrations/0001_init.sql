CREATE TABLE IF NOT EXISTS tts_audio(key TEXT PRIMARY KEY, bin BLOB, created INTEGER);
CREATE TABLE IF NOT EXISTS saves(id TEXT PRIMARY KEY, data TEXT, updated INTEGER);
CREATE TABLE IF NOT EXISTS meta(k TEXT PRIMARY KEY, v TEXT);
CREATE TABLE IF NOT EXISTS diag(id INTEGER PRIMARY KEY AUTOINCREMENT, fam TEXT, at INTEGER, log TEXT, snap TEXT);
CREATE TABLE IF NOT EXISTS evlog(id INTEGER PRIMARY KEY AUTOINCREMENT, fam TEXT, sid TEXT, at INTEGER, tz INTEGER, n INTEGER, ev TEXT, sh TEXT, si TEXT, ns INTEGER DEFAULT 0);
CREATE INDEX IF NOT EXISTS evlog_at ON evlog(at);
